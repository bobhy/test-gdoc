// Command gents generates TypeScript interfaces and default constants from the
// canonical Go settings and RPC DTO structs so Go and TypeScript share a single source of truth.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"reflect"
	"strings"

	"test-gdoc/go/settings"
)

type generatedType struct {
	name string
	doc  string
	typ  reflect.Type
}

func main() {
	outPath := flag.String("out", "src/settings.generated.ts", "output TypeScript file path")
	flag.Parse()

	types := []generatedType{
		{"PluginSettings", "Settings shared between the Obsidian plugin and Go Wasm code.", reflect.TypeFor[settings.PluginSettings]()},
		{"FileMeta", "Metadata for a flat Drive file managed by the plugin.", reflect.TypeFor[settings.FileMeta]()},
		{"ConfigureRequest", "Payload to configure Go-side auth and concurrency limits.", reflect.TypeFor[settings.ConfigureRequest]()},
		{"ConfigureResult", "Response reporting active Go-side configuration.", reflect.TypeFor[settings.ConfigureResult]()},
		{"ListFilesRequest", "Request payload to list flat files in a Drive folder path.", reflect.TypeFor[settings.ListFilesRequest]()},
		{"ListFilesResult", "Result containing the resolved folder ID and flat Drive files.", reflect.TypeFor[settings.ListFilesResult]()},
		{"ReadFileRequest", "Request payload to read a Drive file by ID.", reflect.TypeFor[settings.ReadFileRequest]()},
		{"ReadFileResult", "Result containing Drive file metadata and UTF-8 content.", reflect.TypeFor[settings.ReadFileResult]()},
		{"WriteFileRequest", "Request payload to create or update a Drive file.", reflect.TypeFor[settings.WriteFileRequest]()},
		{"WriteFileResult", "Result containing updated or created Drive file metadata.", reflect.TypeFor[settings.WriteFileResult]()},
		{"MergeAndPushRequest", "Request payload to reconcile local, base, and remote Drive file versions.", reflect.TypeFor[settings.MergeAndPushRequest]()},
		{"MergeAndPushResult", "Result of 3-way N-way reconciliation and Drive push.", reflect.TypeFor[settings.MergeAndPushResult]()},
	}

	var buf bytes.Buffer
	buf.WriteString("// Code generated by go run ./go/cmd/gents; DO NOT EDIT.\n\n")

	for _, gt := range types {
		if err := writeInterface(&buf, gt.name, gt.doc, gt.typ); err != nil {
			fatalf("generate %s: %v", gt.name, err)
		}
		buf.WriteByte('\n')
	}

	if err := writeDefaults(&buf, settings.DefaultSettings()); err != nil {
		fatalf("generate DEFAULT_SETTINGS: %v", err)
	}

	if err := os.WriteFile(*outPath, buf.Bytes(), 0o644); err != nil {
		fatalf("write %s: %v", *outPath, err)
	}
}

func writeInterface(buf *bytes.Buffer, name, doc string, t reflect.Type) error {
	fmt.Fprintf(buf, "/** %s */\n", doc)
	fmt.Fprintf(buf, "export interface %s {\n", name)
	for field := range t.Fields() {
		jsonName := jsonFieldName(field)
		if jsonName == "" {
			continue
		}
		tsType, err := goTypeToTS(field.Type)
		if err != nil {
			return fmt.Errorf("field %s: %w", field.Name, err)
		}
		fmt.Fprintf(buf, "\t%s: %s;\n", jsonName, tsType)
	}
	buf.WriteString("}\n")
	return nil
}

func writeDefaults(buf *bytes.Buffer, defaults settings.PluginSettings) error {
	buf.WriteString("/** Default settings derived from Go's settings.DefaultSettings(). */\n")
	buf.WriteString("export const DEFAULT_SETTINGS: PluginSettings = {\n")

	v := reflect.ValueOf(defaults)
	t := v.Type()
	for i := 0; i < t.NumField(); i++ {
		field := t.Field(i)
		jsonName := jsonFieldName(field)
		if jsonName == "" {
			continue
		}
		valLiteral, err := tsLiteral(v.Field(i).Interface())
		if err != nil {
			return fmt.Errorf("default for %s: %w", field.Name, err)
		}
		fmt.Fprintf(buf, "\t%s: %s,\n", jsonName, valLiteral)
	}
	buf.WriteString("};\n")
	return nil
}

func jsonFieldName(f reflect.StructField) string {
	tag := f.Tag.Get("json")
	if tag == "-" {
		return ""
	}
	if tag == "" {
		return f.Name
	}
	name, _, _ := strings.Cut(tag, ",")
	if name == "" {
		return f.Name
	}
	return name
}

func goTypeToTS(t reflect.Type) (string, error) {
	switch t.Kind() {
	case reflect.String:
		return "string", nil
	case reflect.Bool:
		return "boolean", nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number", nil
	case reflect.Slice:
		elemType, err := goTypeToTS(t.Elem())
		if err != nil {
			return "", fmt.Errorf("slice element: %w", err)
		}
		return elemType + "[]", nil
	case reflect.Struct:
		if t.Name() == "" {
			return "", fmt.Errorf("anonymous structs are not supported")
		}
		return t.Name(), nil
	default:
		return "", fmt.Errorf("unsupported Go kind %s", t.Kind())
	}
}

func tsLiteral(val any) (string, error) {
	if s, ok := val.(string); ok {
		escaped := strings.ReplaceAll(s, `\`, `\\`)
		escaped = strings.ReplaceAll(escaped, `'`, `\'`)
		return "'" + escaped + "'", nil
	}
	raw, err := json.Marshal(val)
	if err != nil {
		return "", err
	}
	return string(raw), nil
}

func fatalf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "gents: "+format+"\n", args...)
	os.Exit(1)
}
