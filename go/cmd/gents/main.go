// Command gents generates TypeScript interfaces and default constants from the
// canonical Go settings structs so Go and TypeScript share a single source of truth.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"reflect"
	"strings"

	"sample-go-plugin/go/settings"
)

func main() {
	outPath := flag.String("out", "src/settings.generated.ts", "output TypeScript file path")
	flag.Parse()

	var buf bytes.Buffer
	buf.WriteString("// Code generated by go run ./go/cmd/gents; DO NOT EDIT.\n\n")

	if err := writeInterface(&buf, "PluginSettings", "Settings shared between the Obsidian plugin and Go Wasm code.", reflect.TypeFor[settings.PluginSettings]()); err != nil {
		fatalf("generate PluginSettings: %v", err)
	}
	buf.WriteByte('\n')

	if err := writeInterface(&buf, "ActionResult", "Structured result returned by the Go Wasm action routine.", reflect.TypeFor[settings.ActionResult]()); err != nil {
		fatalf("generate ActionResult: %v", err)
	}
	buf.WriteByte('\n')

	if err := writeDefaults(&buf, settings.DefaultSettings()); err != nil {
		fatalf("generate DEFAULT_SETTINGS: %v", err)
	}

	if err := os.WriteFile(*outPath, buf.Bytes(), 0o644); err != nil {
		fatalf("write %s: %v", *outPath, err)
	}
}

func writeInterface(buf *bytes.Buffer, name, doc string, t reflect.Type) error {
	fmt.Fprintf(buf, "/** %s */\n", doc)
	fmt.Fprintf(buf, "export interface %s {\n", name)
	for field := range t.Fields() {
		jsonName := jsonFieldName(field)
		if jsonName == "" {
			continue
		}
		tsType, err := goTypeToTS(field.Type)
		if err != nil {
			return fmt.Errorf("field %s: %w", field.Name, err)
		}
		fmt.Fprintf(buf, "\t%s: %s;\n", jsonName, tsType)
	}
	buf.WriteString("}\n")
	return nil
}

func writeDefaults(buf *bytes.Buffer, defaults settings.PluginSettings) error {
	buf.WriteString("/** Default settings derived from Go's settings.DefaultSettings(). */\n")
	buf.WriteString("export const DEFAULT_SETTINGS: PluginSettings = {\n")

	v := reflect.ValueOf(defaults)
	t := v.Type()
	for i := 0; i < t.NumField(); i++ {
		field := t.Field(i)
		jsonName := jsonFieldName(field)
		if jsonName == "" {
			continue
		}
		valLiteral, err := tsLiteral(v.Field(i).Interface())
		if err != nil {
			return fmt.Errorf("default for %s: %w", field.Name, err)
		}
		fmt.Fprintf(buf, "\t%s: %s,\n", jsonName, valLiteral)
	}
	buf.WriteString("};\n")
	return nil
}

func jsonFieldName(f reflect.StructField) string {
	tag := f.Tag.Get("json")
	if tag == "-" {
		return ""
	}
	if tag == "" {
		return f.Name
	}
	name, _, _ := strings.Cut(tag, ",")
	if name == "" {
		return f.Name
	}
	return name
}

func goTypeToTS(t reflect.Type) (string, error) {
	switch t.Kind() {
	case reflect.String:
		return "string", nil
	case reflect.Bool:
		return "boolean", nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number", nil
	default:
		return "", fmt.Errorf("unsupported Go kind %s", t.Kind())
	}
}

func tsLiteral(val any) (string, error) {
	if s, ok := val.(string); ok {
		escaped := strings.ReplaceAll(s, `\`, `\\`)
		escaped = strings.ReplaceAll(escaped, `'`, `\'`)
		return "'" + escaped + "'", nil
	}
	raw, err := json.Marshal(val)
	if err != nil {
		return "", err
	}
	return string(raw), nil
}

func fatalf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "gents: "+format+"\n", args...)
	os.Exit(1)
}
