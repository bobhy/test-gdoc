/**
 * Shared TypeScript interfaces for the Go WebAssembly runtime, JSPI exports/imports,
 * and single-root host injection.
 */

import type { App } from 'obsidian';

/** Shape of the global `Go` class installed by Go's `wasm_exec.js`. */
export interface GoRuntimeInstance {
	importObject: WebAssembly.Imports;
	run(instance: WebAssembly.Instance): Promise<void>;
}

/** Constructor for Go's `wasm_exec.js` runtime class. */
export type GoRuntimeConstructor = new () => GoRuntimeInstance;

/** Typed wrapper over JSPI WebAssembly globals (`Suspending` and `promising`). */
export interface WebAssemblyWithJspi {
	Suspending?: new (fn: (...args: never[]) => unknown) => WebAssembly.ImportValue;
	promising?: <TArgs extends unknown[], TResult>(
		fn: (...args: TArgs) => TResult,
	) => (...args: TArgs) => Promise<Awaited<TResult>>;
	instantiate: typeof WebAssembly.instantiate;
}

/** Wasm exports generated by `//go:wasmexport` alongside Go's linear memory (`mem`). */
export interface WasmJspiExports extends WebAssembly.Exports {
	mem: WebAssembly.Memory;
	getScratchHeader(this: void): number;
	getMergeDirectHeader(this: void): number;
	allocBuffer(this: void, size: number, outHeaderPtr: number): number;
	releaseBuffer(this: void, bufId: number): void;
	getLastJspiError(this: void, outHeaderPtr: number): number;
	applyPullBatch(
		this: void,
		batchId: number,
		syncFolderBufId: number,
		outHeaderPtr: number,
	): number;
	preparePushInputs(this: void, syncFolderBufId: number, fileNameBufId: number): number;
	applyPreparedPush(this: void, batchId: number, outHeaderPtr: number): number;
	collectVaultStats(this: void, syncFolderBufId: number): number;
	readVaultFilesForScan(this: void, scanId: number): number;
	reconcileTextDirect(
		this: void,
		baseBufId: number,
		localBufId: number,
		remoteBufId: number,
		outMergeHeaderPtr: number,
	): number;
}

/** Promisified JSPI entrypoints created with `WebAssembly.promising(...)`. */
export interface PromisedWasmExports {
	applyPullBatch(batchId: number, syncFolderBufId: number, outHeaderPtr: number): Promise<number>;
	preparePushInputs(syncFolderBufId: number, fileNameBufId: number): Promise<number>;
	applyPreparedPush(batchId: number, outHeaderPtr: number): Promise<number>;
	collectVaultStats(syncFolderBufId: number): Promise<number>;
	readVaultFilesForScan(scanId: number): Promise<number>;
}

/** Minimal Obsidian module subset injected once onto `window.__testgdocHost`. */
export interface ObsidianHostModule {
	requestUrl: unknown;
	Notice: unknown;
}

/** Single-root host state mounted once on `window.__testgdocHost` during Wasm init. */
export interface WasmHostCallbacks {
	app: App;
	obsidian: ObsidianHostModule;
}

/** Functions exported onto `window.__testgdoc` by `go/cmd/plugin`. */
export interface WasmBridgeApi {
	invoke(method: string, payloadJson: string): Promise<string>;
	shutdown(): void;
}

/** Window extension exposing the Go runtime constructor, host root, and Wasm bridge. */
export interface WasmWindowGlobals {
	Go?: GoRuntimeConstructor;
	__testgdoc?: WasmBridgeApi;
	__testgdocHost?: WasmHostCallbacks;
}
